//! Prototype recursive codegen: generates plain Rust source (as a `String`, not via an AST
//! library - this isn't trying to be a second copy of doodle's own `rust_ast`/`ToFragment`
//! pipeline) for one recursive batch, proving the two open questions from the extension plan:
//!
//! 1. Does `FormatType::Ref` drive a correct `Box<Self>`-indirected Rust type?
//! 2. Does a compiled batch turn into mutually recursive Rust `fn`s, with `RecVar(ix)` becoming
//!    a direct sibling call?
//!
//! Deliberately scoped to the `Decoder`/`FormatType` shapes needed to express the grammars
//! already used throughout this plan (self- and mutually-recursive `Union`/`Tuple`/`Byte`
//! structures) - `Repeat*`, `Maybe`, `Peek*`, `Parallel`, `Slice`, `WithRelativeOffset` are all
//! real features with nothing left to prove about *this* step's question, so they're an explicit
//! `Err`, not attempted here. Built directly on the already-*compiled* `Decoder`/`Program` (not
//! raw `Format`): `Union` disambiguation is already solved by `MatchTree`/`Compiler`, so codegen
//! only has to translate an already-built decision tree into an equivalent Rust `match`, not
//! re-derive one.
//!
//! Also deliberately narrow in a second way: this only generates code for *one* recursive batch
//! at a time, and `Decoder::Call` (an `ItemVar` reference reaching some format outside the
//! current batch) is unsupported - `Program` doesn't track which `FormatId` a given compiled
//! slot came from, so there's no way to know what to call. None of this step's target grammars
//! need it (`RecVar`, resolved without any slot lookup at all via its own relative batch index,
//! covers every intra-batch reference), so this wasn't worth solving for a prototype.

use std::fmt::Write as _;

use anyhow::{Result as AResult, anyhow};

use crate::{
    BaseType, Format, FormatId, FormatModule, FormatType, Label, MatchTree, RecurseCtx, Span,
    TypeShape,
    decoder::{Compiler, Decoder, Value},
};

/// Everything compiled for one recursive batch: the module-level `FormatId` span, and each
/// member's declared name / solved type / compiled decoder, all in span order (so member `ix`'s
/// entry corresponds to `Format::RecVar(ix)` within the batch).
pub struct CompiledBatch<'a> {
    span: Span<FormatId>,
    names: Vec<&'a Label>,
    types: Vec<FormatType>,
    decoders: Vec<Decoder>,
}

/// Compiles every member of the recursive batch containing `entry_level`, in one pass -
/// `Compiler::compile_program`'s own `Format::ItemVar` handling already queues every batch
/// member together (see `queue_compile_batch`) whenever *any* member is referenced, so a single
/// call compiling `entry_level` alone yields all of them.
pub fn compile_batch(module: &FormatModule, entry_level: FormatId) -> AResult<CompiledBatch<'_>> {
    let span = module
        .get_batch(entry_level)
        .ok_or_else(|| anyhow!("level {entry_level} is not part of a recursive batch"))?;
    let program =
        Compiler::compile_program(module, &Format::ItemVar(entry_level), RecurseCtx::NonRec)?;
    // decoders[0] is the ItemVar(entry_level) wrapper itself (a Decoder::Call); the batch's own
    // members were queued right after it, contiguously, in the same order as `span`.
    let batch_len = span.end - span.start + 1;
    let base = program.decoders.len() - batch_len;
    let mut names = Vec::with_capacity(batch_len);
    let mut types = Vec::with_capacity(batch_len);
    let mut decoders = Vec::with_capacity(batch_len);
    for ix in 0..batch_len {
        let level = span.start + ix;
        names.push(module.get_name(level));
        let (decoder, ty) = &program.decoders[base + ix];
        types.push(ty.clone());
        decoders.push(decoder.clone());
    }
    Ok(CompiledBatch {
        span,
        names,
        types,
        decoders,
    })
}

/// Generates one Rust source string containing a type declaration and a `decode_*` function for
/// every member of `batch`, calling each other directly by name for `RecVar` references.
pub fn generate_batch_source(batch: &CompiledBatch<'_>) -> AResult<String> {
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by doodle-rec's codegen prototype - do not hand-edit."
    )?;
    for ix in 0..batch.names.len() {
        writeln!(out)?;
        write_type_decl(&mut out, batch, ix)?;
    }
    for ix in 0..batch.names.len() {
        writeln!(out)?;
        write_decode_fn(&mut out, batch, ix)?;
    }
    Ok(out)
}

fn write_type_decl(out: &mut String, batch: &CompiledBatch<'_>, ix: usize) -> AResult<()> {
    let name = type_name(batch.names[ix]);
    match &batch.types[ix] {
        FormatType::Shape(TypeShape::Union(variants)) => {
            writeln!(out, "pub enum {name} {{")?;
            for (label, ty) in variants {
                let inner = rust_type(batch, ty)?;
                writeln!(out, "    {}({inner}),", variant_name(label))?;
            }
            writeln!(out, "}}")?;
        }
        other => {
            let inner = rust_type(batch, other)?;
            writeln!(out, "pub type {name} = {inner};")?;
        }
    }
    Ok(())
}

fn write_decode_fn(out: &mut String, batch: &CompiledBatch<'_>, ix: usize) -> AResult<()> {
    let name = fn_name(batch.names[ix]);
    let ty = type_name(batch.names[ix]);
    writeln!(
        out,
        "pub fn {name}(input: &[u8]) -> Result<({ty}, &[u8]), String> {{"
    )?;
    let body = gen_decoder(batch, &batch.decoders[ix], &batch.types[ix], Some(ix))?;
    writeln!(out, "    {body}")?;
    writeln!(out, "}}")?;
    Ok(())
}

/// Translates one compiled `Decoder` into a Rust block-expression of type
/// `Result<(T, &[u8]), String>`, given an ambient `input: &[u8]` binding already in scope.
/// `enclosing_enum`, when `Some`, is the batch member index whose `enum` a `Decoder::Variant`
/// directly beneath a `Decoder::Branch` should construct into - the only place `Union` types are
/// supported (matching `write_type_decl`, which only ever emits an `enum` at a batch member's
/// own top level, never nested).
fn gen_decoder(
    batch: &CompiledBatch<'_>,
    d: &Decoder,
    ty: &FormatType,
    enclosing_enum: Option<usize>,
) -> AResult<String> {
    match d {
        Decoder::FailWith(msg) => Ok(format!("{{ Err(format!({msg:?})) }}")),
        Decoder::EndOfInput => Ok(
            "{ if input.is_empty() { Ok(((), input)) } else { Err(\"expected end of input\".to_string()) } }"
                .to_string(),
        ),
        Decoder::Byte(bs) => {
            let pattern = bs
                .iter()
                .map(|b| format!("{b}u8"))
                .collect::<Vec<_>>()
                .join(" | ");
            if pattern.is_empty() {
                Ok("{ Err(\"unsatisfiable byte set\".to_string()) }".to_string())
            } else {
                Ok(format!(
                    "{{ match input.first().copied() {{ Some(b) if matches!(b, {pattern}) => Ok((b, &input[1..])), _ => Err(\"byte mismatch\".to_string()) }} }}"
                ))
            }
        }
        Decoder::Compute(expr) => {
            let lit = value_to_rust_literal(&expr.eval())?;
            Ok(format!("{{ Ok::<_, String>(({lit}, input)) }}"))
        }
        Decoder::Variant(label, d) => {
            let ix = enclosing_enum
                .ok_or_else(|| anyhow!("codegen: Variant outside a batch member's own Union"))?;
            let FormatType::Shape(TypeShape::Union(variants)) = &batch.types[ix] else {
                return Err(anyhow!(
                    "codegen: enclosing_enum's own type isn't a Union - inconsistent state"
                ));
            };
            let inner_ty = variants
                .get(label)
                .ok_or_else(|| anyhow!("codegen: variant {label} not found in enclosing Union"))?;
            let inner = gen_decoder(batch, d, inner_ty, None)?;
            let enum_name = type_name(batch.names[ix]);
            let ctor = variant_name(label);
            Ok(format!(
                "{{ let (v, input) = {inner}?; Ok::<_, String>(({enum_name}::{ctor}(v), input)) }}"
            ))
        }
        Decoder::Branch(tree, ds) => {
            let dispatch = gen_match_tree(tree, 0);
            let mut arms = String::new();
            for (i, d) in ds.iter().enumerate() {
                let arm = gen_decoder(batch, d, ty, enclosing_enum)?;
                writeln!(arms, "        {i} => {arm},")?;
            }
            Ok(format!(
                "{{ let branch_ix: Result<usize, String> = {dispatch}; match branch_ix? {{\n{arms}        _ => unreachable!(\"MatchTree produced an out-of-range branch index\"),\n    }} }}"
            ))
        }
        Decoder::Tuple(ds) => {
            let FormatType::Shape(TypeShape::Tuple(field_types)) = ty else {
                return Err(anyhow!("codegen: Tuple decoder without a Tuple FormatType"));
            };
            if ds.is_empty() {
                return Ok("{ Ok::<_, String>(((), input)) }".to_string());
            }
            let mut block = String::from("{\n");
            for (i, (d, field_ty)) in ds.iter().zip(field_types).enumerate() {
                let sub = gen_decoder(batch, d, field_ty, None)?;
                writeln!(block, "        let (v{i}, input) = {sub}?;")?;
            }
            let elems = (0..ds.len())
                .map(|i| format!("v{i}"))
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(block, "        Ok::<_, String>((({elems}), input))\n    }}")?;
            Ok(block)
        }
        Decoder::Seq(ds) => {
            let FormatType::Shape(TypeShape::Seq(elem_ty)) = ty else {
                return Err(anyhow!("codegen: Seq decoder without a Seq FormatType"));
            };
            let mut block = String::from("{\n        let mut v = Vec::new();\n");
            for d in ds {
                let sub = gen_decoder(batch, d, elem_ty, None)?;
                writeln!(block, "        let (vi, input) = {sub}?; v.push(vi);")?;
                // NOTE: `input` is intentionally rebound each iteration below via shadowing in
                // the emitted source, not here - this loop just emits one `let` per element.
            }
            // Re-thread `input` correctly: each emitted `let (vi, input) = ...` above shadows
            // the same name, so by construction the last one is already the correct final
            // position - only the trailing `Ok` needs to reference it.
            writeln!(block, "        Ok::<_, String>((v, input))\n    }}")?;
            Ok(block)
        }
        Decoder::CallRec(_slot, batch_ix) => {
            let target = *batch_ix;
            if target >= batch.names.len() {
                return Err(anyhow!("codegen: RecVar({target}) out of range for this batch"));
            }
            let callee = fn_name(batch.names[target]);
            // `ty` here is *this call site's* expected type, not the callee's own type - the two
            // only diverge in exactly one case: `FormatType::Ref(level)`, which `infer_type`
            // produces precisely when `level` is still open on the current member's own
            // resolution stack (a true cycle back to an ancestor), and which `rust_type` maps to
            // `Box<...>`. Every other in-batch `RecVar` reference gets the callee's structure
            // inlined verbatim (see the mutual-recursion test), so the callee's own return type
            // already matches `ty` with no wrapping needed.
            let target_level = batch.span.start + target;
            match ty {
                FormatType::Ref(level) if *level == target_level => {
                    Ok(format!(
                        "{{ let (v, input) = {callee}(input)?; Ok::<_, String>((Box::new(v), input)) }}"
                    ))
                }
                _ => Ok(format!("{{ {callee}(input) }}")),
            }
        }
        Decoder::Call(_) => Err(anyhow!(
            "codegen: Decoder::Call (a reference to a format outside this batch) is not supported by this prototype"
        )),
        other => Err(anyhow!(
            "codegen: unsupported decoder shape (out of scope for this prototype): {other:?}"
        )),
    }
}

/// Translates a compiled `MatchTree`'s lookahead into an equivalent Rust expression of type
/// `Result<usize, String>`, mirroring `MatchTree::matches`'s own recursive logic exactly - a
/// `match` on `input.get(depth)` (peeking, not consuming) at each level, falling back to
/// `tree.accept()` once the input is exhausted or no branch's byte-set contains the next byte.
fn gen_match_tree(tree: &MatchTree, depth: usize) -> String {
    let fallback = match tree.accept() {
        Some(ix) => format!("Ok({ix})"),
        None => "Err(\"no valid branch\".to_string())".to_string(),
    };
    if tree.branches().is_empty() {
        return fallback;
    }
    let mut arms = String::new();
    for (bs, sub) in tree.branches() {
        let pattern = bs
            .iter()
            .map(|b| format!("{b}u8"))
            .collect::<Vec<_>>()
            .join(" | ");
        let rest = gen_match_tree(sub, depth + 1);
        let _ = write!(arms, "Some(b) if matches!(*b, {pattern}) => {{ {rest} }}, ");
    }
    format!("match input.get({depth}) {{ {arms}_ => {fallback} }}")
}

fn value_to_rust_literal(v: &Value) -> AResult<String> {
    match v {
        Value::U8(n) => Ok(format!("{n}u8")),
        Value::U16(n) => Ok(format!("{n}u16")),
        Value::U32(n) => Ok(format!("{n}u32")),
        Value::U64(n) => Ok(format!("{n}u64")),
        Value::Bool(b) => Ok(b.to_string()),
        Value::Char(c) => Ok(format!("{c:?}")),
        other => Err(anyhow!(
            "codegen: Compute producing a composite value ({other:?}) is not supported by this prototype"
        )),
    }
}

fn rust_type(batch: &CompiledBatch<'_>, ty: &FormatType) -> AResult<String> {
    match ty {
        FormatType::Base(BaseType::U8) => Ok("u8".to_string()),
        FormatType::Base(BaseType::U16) => Ok("u16".to_string()),
        FormatType::Base(BaseType::U32) => Ok("u32".to_string()),
        FormatType::Base(BaseType::U64) => Ok("u64".to_string()),
        FormatType::Base(BaseType::Bool) => Ok("bool".to_string()),
        FormatType::Base(BaseType::Char) => Ok("char".to_string()),
        FormatType::Ref(level) => {
            if *level >= batch.span.start && *level <= batch.span.end {
                let ix = level - batch.span.start;
                Ok(format!("Box<{}>", type_name(batch.names[ix])))
            } else {
                Err(anyhow!(
                    "codegen: Ref to level {level}, outside the current batch - not supported by this prototype (Program doesn't track slot-to-FormatId, so there's no way to name it)"
                ))
            }
        }
        FormatType::Shape(TypeShape::Tuple(fields)) => {
            if fields.is_empty() {
                Ok("()".to_string())
            } else {
                let parts = fields
                    .iter()
                    .map(|f| rust_type(batch, f))
                    .collect::<AResult<Vec<_>>>()?;
                Ok(format!("({})", parts.join(", ")))
            }
        }
        FormatType::Shape(TypeShape::Seq(elem)) => Ok(format!("Vec<{}>", rust_type(batch, elem)?)),
        FormatType::Shape(TypeShape::Option(inner)) => {
            Ok(format!("Option<{}>", rust_type(batch, inner)?))
        }
        FormatType::Shape(TypeShape::Union(_)) => Err(anyhow!(
            "codegen: a Union type nested inside another type isn't supported by this prototype (only at a batch member's own top level)"
        )),
        FormatType::Void => Err(anyhow!("codegen: cannot generate a Rust type for Void")),
        FormatType::Any => Err(anyhow!(
            "codegen: cannot generate a Rust type for an unresolved Any"
        )),
    }
}

/// PascalCase Rust type identifier derived from a declared format name (e.g. "test.peano" ->
/// "TestPeano"). Prototype-grade sanitization: splits on any non-alphanumeric byte, capitalizes
/// each piece.
fn type_name(label: &Label) -> String {
    let mut out = String::new();
    for word in label.split(|c: char| !c.is_alphanumeric()) {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.extend(chars);
        }
    }
    if out.is_empty() {
        "Anon".to_string()
    } else {
        out
    }
}

fn fn_name(label: &Label) -> String {
    let mut out = String::from("decode_");
    for (i, word) in label
        .split(|c: char| !c.is_alphanumeric())
        .filter(|s| !s.is_empty())
        .enumerate()
    {
        if i > 0 {
            out.push('_');
        }
        out.push_str(&word.to_lowercase());
    }
    out
}

fn variant_name(label: &Label) -> String {
    type_name(label)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Label;
    use doodle::byte_set::ByteSet;

    fn peano_module() -> (FormatModule, FormatId) {
        let peano = Format::Union(vec![
            Format::Variant(
                Label::Borrowed("Z"),
                Box::new(Format::Byte(ByteSet::from([b'Z']))),
            ),
            Format::Variant(
                Label::Borrowed("S"),
                Box::new(Format::Tuple(vec![
                    Format::Byte(ByteSet::from([b'S'])),
                    Format::RecVar(0),
                ])),
            ),
        ]);
        let mut module = FormatModule::new();
        let frefs = module.declare_rec_formats(vec![(Label::Borrowed("test.peano"), peano)]);
        let level = frefs[0].get_level();
        (module, level)
    }

    #[test]
    fn peano_type_is_self_referential_enum_with_box() -> AResult<()> {
        let (module, level) = peano_module();
        let batch = compile_batch(&module, level)?;
        let src = generate_batch_source(&batch)?;
        assert!(src.contains("pub enum TestPeano"));
        assert!(src.contains("Box<TestPeano>"), "source was:\n{src}");
        assert!(src.contains("pub fn decode_test_peano"));
        // The recursive call must be a direct sibling call, not any kind of indirection.
        assert!(
            src.contains("decode_test_peano(input)"),
            "source was:\n{src}"
        );
        Ok(())
    }

    /// Two-member mutually-recursive batch (not just self-recursive), proving `RecVar` becomes a
    /// direct call to a genuinely *different* sibling function, not just "call myself again".
    fn ping_pong_module() -> (FormatModule, FormatId) {
        // ping := 'A' ping | 'Z'   (via pong as an intermediary, to force real mutual recursion)
        let ping = Format::Union(vec![
            Format::Variant(
                Label::Borrowed("Done"),
                Box::new(Format::Byte(ByteSet::from([b'Z']))),
            ),
            Format::Variant(
                Label::Borrowed("More"),
                Box::new(Format::Tuple(vec![
                    Format::Byte(ByteSet::from([b'A'])),
                    Format::RecVar(1), // -> pong
                ])),
            ),
        ]);
        let pong = Format::Tuple(vec![Format::Byte(ByteSet::from([b'B'])), Format::RecVar(0)]); // -> ping
        let mut module = FormatModule::new();
        let frefs = module.declare_rec_formats(vec![
            (Label::Borrowed("ping"), ping),
            (Label::Borrowed("pong"), pong),
        ]);
        let level = frefs[0].get_level();
        (module, level)
    }

    #[test]
    fn mutual_recursion_calls_the_correct_sibling_by_name() -> AResult<()> {
        let (module, level) = ping_pong_module();
        let batch = compile_batch(&module, level)?;
        let src = generate_batch_source(&batch)?;
        assert!(src.contains("pub enum Ping"));
        assert!(src.contains("pub type Pong = "));
        // `FormatDecl::solve_type_with` only ever leaves behind a `FormatType::Ref` at a batch
        // member's own true self-cycle point (the level currently open on *its own* resolution
        // stack) - a `RecVar` reaching a sibling that isn't itself mid-resolution gets that
        // sibling's structure inlined instead (see `declare_rec_formats`: each member solves with
        // its own fresh `visited` set). So `ping`'s "More" field is pong's *inlined* tuple shape,
        // not a `Box<Pong>` - only `pong`'s own field (which cycles back to `ping`, still open on
        // the stack at that point) becomes a `Ref`, hence `Box<Ping>` here rather than `Box<Pong>`.
        assert!(src.contains("Box<Ping>"), "source was:\n{src}");
        assert!(src.contains("pub fn decode_ping"));
        assert!(src.contains("pub fn decode_pong"));
        // ping's "More" arm must call pong directly, and pong must call ping directly back.
        assert!(src.contains("decode_pong(input)"), "source was:\n{src}");
        assert!(src.contains("decode_ping(input)"), "source was:\n{src}");
        Ok(())
    }
}
